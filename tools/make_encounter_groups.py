"""Builds mod/FFRRandomizer/Scripts/EncounterGroups.lua from the JSON export.

Lists the battle groups that the area encounter tables can roll, so the enemy
shuffle only touches random encounters, never scripted fights.
Run: py -3 -I tools/make_encounter_groups.py
"""
import json
import pathlib

EXPORT = pathlib.Path("D:/AI Stuff/Exports/FFR Rando/datatables.json")
OUT = pathlib.Path(__file__).resolve().parent.parent / "mod/FFRRandomizer/Scripts/EncounterGroups.lua"

tables = json.loads(EXPORT.read_text(encoding="utf-8"))["Tables"]
groups = set()
for table in tables:
    if table["RowStructName"] == "ENCOUNT_GROUP_DATA":
        for row in table["Rows"].values():
            if row.get("battleGroupId", -1) > 0:
                groups.add(row["battleGroupId"])

lines = ["-- Generated by tools/make_encounter_groups.py. Do not edit by hand.",
         "-- Battle group IDs that random encounters can roll.", "return {"]
lines += [f"    [{group}] = true," for group in sorted(groups)]
lines.append("}")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Wrote {len(groups)} encounter groups to {OUT}")
