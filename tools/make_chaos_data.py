"""Builds mod/FFRRandomizer/Scripts/ChaosData.lua from the CSV and JSON export.

Names for the spoiler log of the gear, enemy and We are Chaos options: every
passive skill, and the members of the enums the mod reads as bare numbers
(elements, status conditions and the gear stat keys).
Run: py -3 -I tools/make_chaos_data.py
"""
import csv
import json
import pathlib

EXPORT = pathlib.Path("D:/AI Stuff/Exports/FFR Rando")
OUT = pathlib.Path(__file__).resolve().parent.parent / "mod/FFRRandomizer/Scripts/ChaosData.lua"
ENUMS = {"elements": "eElement", "statuses": "eUnitStatusCondition", "stats": "eUnitParameterType"}


def lua_text(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


with open(EXPORT / "DT_PassiveSkillData.csv", encoding="utf-8-sig") as file:
    passives = {int(r["ID"]): r["Name (read only)"] for r in csv.DictReader(file)}

members = {}
for table in json.loads((EXPORT / "datatables.json").read_text(encoding="utf-8"))["Tables"]:
    for field in table.get("Fields") or []:
        if field.get("EnumName") in ENUMS.values() and field.get("Members"):
            members.setdefault(field["EnumName"], field["Members"])

lines = ["-- Generated by tools/make_chaos_data.py. Do not edit by hand.", "return {"]
for key, enum in ENUMS.items():
    # Enum value i is members[i]; the trailing Num and _MAX entries aren't real values.
    lines.append(f"    {key} = {{")
    lines += [f"        [{i}] = {lua_text(name)}," for i, name in enumerate(members[enum])
              if name != "Num" and not name.endswith("_MAX")]
    lines.append("    },")
lines.append("    passives = {")
lines += [f"        [{i}] = {lua_text(name)}," for i, name in sorted(passives.items()) if name]
lines += ["    },", "}"]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"Wrote {len(passives)} passive names and {len(ENUMS)} enums to {OUT}")
