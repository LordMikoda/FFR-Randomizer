"""Builds mod/FFRRandomizer/Scripts/TrapData.lua from the JSON export.

Not used since 0.8.0: the game's chest traps couldn't start a fight (see the FFR
Randomizer note), so the mod no longer ships TrapData.lua. Kept for a later try.

Trapped chests need two lookups the game doesn't keep in one place:
- the level of each map that has chests: the average enemy level of the
  battles its own encounter tables roll (DT_<map key>_*_Encount), else its
  DangerLevel, else the lowest area level in the same region (towns);
- the average enemy level of every random-encounter battle group.
Run: py -3 -I tools/make_trap_data.py
"""
import collections
import csv
import json
import pathlib
import re

EXPORT = pathlib.Path("D:/AI Stuff/Exports/FFR Rando")
OUT = pathlib.Path(__file__).resolve().parent.parent / "mod/FFRRandomizer/Scripts/TrapData.lua"

tables = {}
for table in json.loads((EXPORT / "datatables.json").read_text(encoding="utf-8"))["Tables"]:
    tables[table["GamePath"].split("/")[-1].replace(".uasset", "")] = table


def rows(name):
    found = tables[name]["Rows"]
    return found if isinstance(found, dict) else {str(i): r for i, r in enumerate(found)}


unit_level = {r["ID"]: r.get("Level", 0) for r in rows("DT_UnitParameter").values()}
# The JSON leaves list fields out, so the units come from the CSV.
group_units = {}
with open(EXPORT / "DT_BattleGroup.csv", encoding="utf-8-sig", newline="") as f:
    for r in csv.DictReader(f):
        ids = [r.get(f"UnitIdList[{i}]") for i in range(8)]
        group_units[int(r["ID"])] = [int(u) for u in ids if u not in (None, "") and int(u) > 0]

# Every battle group each encounter table rolls, by the map key its name
# points at. Names vary: DT_01Gra_40_01_Encount, DT_02Lan_Dng_40_01_Encount,
# DT_Dng_04Dir_41_2_Encount give 01Gra_40, 02Lan_40, 04Dir_41; world map
# tables (DT_03Kol_Wld_02_Encount) give 03Kol_Wld. Bounty tables are skipped.
def table_key(name):
    if not name.endswith("_Encount") or "Bounty" in name:
        return None
    region = re.search(r"(\d\d[A-Za-z]+)", name)
    if not region:
        return None
    rest = name[region.end():]
    if "_Wld" in rest:
        return region.group(1) + "_Wld"
    number = re.search(r"_(4\d)(?:_|$)", rest)
    return region.group(1) + "_" + number.group(1) if number else None


map_groups = collections.defaultdict(set)
for name in tables:
    key = table_key(name)
    if key:
        for r in rows(name).values():
            group = r.get("battleGroupId", -1)
            if 100 <= group < 300000:
                map_groups[key].add(group)


def group_level(group):
    levels = [unit_level[u] for u in group_units.get(group, []) if unit_level.get(u)]
    return sum(levels) / len(levels) if levels else None


groups = {}
for groups_of_map in map_groups.values():
    for group in groups_of_map:
        level = group_level(group)
        if level is not None:
            groups[group] = round(level, 1)

maps = rows("CDT_MapData_Prod")
chest_maps = {r["mapId"] for r in rows("CDT_MapGimmickTreasureBox").values()}
key_of = {r["ID"]: key for key, r in maps.items() if "ID" in r}
# A few chest maps have no map row; their chests' names (Dng_02Lan_41_0) still
# carry the map key.
for name, r in rows("CDT_MapGimmickTreasureBox").items():
    match = re.search(r"(\d\d[A-Za-z]+_\d+)", name)
    if r["mapId"] not in key_of and match:
        key_of[r["mapId"]] = match.group(1)
area = {}
for map_id in sorted(chest_maps):
    key = key_of.get(map_id)
    levels = [groups[g] for g in map_groups.get(key, ()) if g in groups]
    if levels:
        area[map_id] = (round(sum(levels) / len(levels), 1), key, "encounters")
    elif key in maps and maps[key].get("DangerLevel", 0) > 0:
        area[map_id] = (float(maps[key]["DangerLevel"]), key, "danger level")
# Towns and other maps with neither: the region's world map level, else the
# lowest area level in the region.
def average(keys):
    levels = [groups[g] for k in keys for g in map_groups.get(k, ()) if g in groups]
    return round(sum(levels) / len(levels), 1) if levels else None


for map_id in sorted(chest_maps):
    if map_id in area:
        continue
    key = key_of.get(map_id) or ""
    region = key.split("_")[0]
    world = average([region + "_Wld"]) if region else None
    near = [lv for m, (lv, k, _) in area.items() if k.split("_")[0] == region and region]
    if world is not None:
        area[map_id] = (world, key, "region world map")
    else:
        area[map_id] = (min(near) if near else 1.0, key or str(map_id), "region")

lines = ["-- Generated by tools/make_trap_data.py. Do not edit by hand.", "return {",
         "    -- Average enemy level of each random-encounter battle group.", "    groups = {"]
lines += [f"        [{g}] = {lv}," for g, lv in sorted(groups.items())]
lines += ["    },", "    -- Level of each map that has chests: { level, map key }.", "    maps = {"]
lines += [f'        [{m}] = {{ {lv}, "{k}" }}, -- {how}' for m, (lv, k, how) in sorted(area.items())]
lines += ["    },", "}"]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
how = collections.Counter(h for _, _, h in area.values())
print(f"Wrote {len(groups)} groups and {len(area)} chest maps ({dict(how)}) to {OUT}")
