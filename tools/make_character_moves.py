"""Builds mod/FFRRandomizer/Scripts/CharacterMoves.lua from the CSV export.

The character shuffles need what the mod can't read from the game in a usable
form (UE4SS hands enums back as bare numbers): each playable character's level
table and attack type, which level-up skills are finishers (LimitBurst), which
must stay with their owner, and the skill names for the spoiler log.
Stays put: Mechabo skills and any skill that loads an extra unit (Lid's
Mechabo), and Darkfina's Witching Hour pair, which only works together.
Run: py -3 -I tools/make_character_moves.py
"""
import csv
import json
import pathlib

EXPORT = pathlib.Path("D:/AI Stuff/Exports/FFR Rando")
OUT = pathlib.Path(__file__).resolve().parent.parent / "mod/FFRRandomizer/Scripts/CharacterMoves.lua"
# Level table suffix for each playable unit, in unit ID order.
CHARACTERS = {1001: "Rain", 1002: "Lasswell", 1003: "Fina", 1004: "Lid", 1005: "Nichol",
              1006: "Darkfina", 1007: "Jake", 1008: "Sakura"}
MODE_PAIRS = {408090, 408150}  # Witching Hour, End Witching Hour


def rows(name):
    with open(EXPORT / f"{name}.csv", encoding="utf-8-sig") as file:
        return list(csv.DictReader(file))


def lua_text(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


skills = {int(r["ID"]): r for r in rows("DT_SkillData")}
playable = {int(r["ID"]): r for r in rows("DT_PlayableUnitParameter")}
loads_unit = {int(r["LoadSkillId"]) for r in rows("DT_BtlSkillLoadUnitData")}
# ePlayableUnit, the enum of DT_SkillData.hasUnit: the Limit Burst menu lists the
# finishers whose hasUnit is the character, so a moved finisher needs its new owner's.
skill_fields = next(t for t in json.loads((EXPORT / "datatables.json").read_text(encoding="utf-8"))["Tables"]
                    if t["GamePath"].endswith("Skill/DT_SkillData.uasset"))["Fields"]
playable_enum = next(f["Members"] for f in skill_fields if f["Name"] == "hasUnit")

learned = set()
for table in CHARACTERS.values():
    for row in rows(f"DT_UnitLevelParameter{table}"):
        n = 0
        while f"AddSkills[{n}]" in row:
            value = row[f"AddSkills[{n}]"]
            if value not in ("", "-1", "0"):
                learned.add(int(value))
            n += 1

finishers = sorted(i for i in learned if skills[i]["skillAttrType"] == "LimitBurst")
fixed = sorted(i for i in learned
               if skills[i]["skillAttrType"] == "Mechabo" or i in loads_unit or i in MODE_PAIRS)
finishers = [i for i in finishers if i not in fixed]

lines = ["-- Generated by tools/make_character_moves.py. Do not edit by hand.",
         "return {",
         "    -- Playable characters: unit ID, level table suffix, whether attackType is Physic,",
         "    -- and owner, the character's ePlayableUnit value for DT_SkillData.hasUnit.",
         "    characters = {"]
for unit, table in CHARACTERS.items():
    physical = "true" if playable[unit]["attackType"] == "Physic" else "false"
    owner = playable_enum.index(table)
    lines.append(f'        {{ unit = {unit}, table = "{table}", name = {lua_text(playable[unit]["Name (read only)"])}, physical = {physical}, owner = {owner} }},')
lines += ["    },", "    -- Level-up finishers (LimitBurst) that can move.", "    finishers = {"]
lines += [f"        [{i}] = true, -- {skills[i]['Name (read only)']}" for i in finishers]
lines += ["    },", "    -- Level-up skills that stay with their owner.", "    fixed = {"]
lines += [f"        [{i}] = true, -- {skills[i]['Name (read only)']}" for i in fixed]
lines += ["    },", "    names = {"]
lines += [f"        [{i}] = {lua_text(skills[i]['Name (read only)'])}," for i in sorted(learned)]
lines += ["    },", "}"]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"Wrote {len(CHARACTERS)} characters, {len(finishers)} finishers, {len(fixed)} fixed skills and "
      f"{len(learned)} names to {OUT}")
