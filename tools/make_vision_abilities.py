"""Builds mod/FFRRandomizer/Scripts/VisionAbilities.lua from the CSV export.

The Vision ability shuffle needs three things the game tables don't say in a
form the mod can read: which Visions are Physical (attackType is an enum, and
UE4SS hands enums back as bare numbers), which passives are near-copies of one
stat bonus, such as Speed +5%, +10% and +20%, and the ability names for the
spoiler log.
Run: py -3 -I tools/make_vision_abilities.py
"""
import csv
import pathlib
import re

EXPORT = pathlib.Path("D:/AI Stuff/Exports/FFR Rando")
OUT = pathlib.Path(__file__).resolve().parent.parent / "mod/FFRRandomizer/Scripts/VisionAbilities.lua"
MASTERY_TABLES = ("DT_VisionAwakeningMasteryData", "DT_VisionSynchroMasteryData")
# "Speed +10%" -> family "Speed". Only plain stat bonuses match.
FAMILY = re.compile(r"^(.*?)\s*\+\s*\d+%$")


def rows(name):
    with open(EXPORT / f"{name}.csv", encoding="utf-8-sig") as file:
        return list(csv.DictReader(file))


def lua_text(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


skills = {int(r["ID"]): r["Name (read only)"] for r in rows("DT_SkillData")}
passives = {int(r["ID"]): r["Name (read only)"] for r in rows("DT_PassiveSkillData")}
visions = rows("DT_VisionItemData")

used_active, used_passive = set(), set()
for table in MASTERY_TABLES:
    for row in rows(table):
        n = 0
        while f"detailData[{n}].parameterType" in row:
            kind, value = row[f"detailData[{n}].parameterType"], int(row[f"detailData[{n}].params[0]"])
            if kind == "ActiveSkill":
                used_active.add(value)
            elif kind == "PassiveSkill":
                used_passive.add(value)
            n += 1
used_active |= {int(v["finishBlowSkill"]) for v in visions}

families = {}
for id in sorted(used_passive):
    match = FAMILY.match(passives[id])
    if match:
        families[id] = match.group(1)

lines = ["-- Generated by tools/make_vision_abilities.py. Do not edit by hand.",
         "return {",
         "    -- Visions whose attackType is Physic. The rest count as Magic, Ayaka (None) included.",
         "    physical = {"]
lines += [f"        [{v['ID']}] = true, -- {v['Name (read only)']}"
          for v in sorted(visions, key=lambda v: int(v["ID"])) if v["attackType"] == "Physic"]
lines += ["    },", "    -- Stat passives that are near-copies of each other share a family.", "    families = {"]
lines += [f"        [{id}] = {lua_text(family)}, -- {passives[id]}" for id, family in families.items()]
lines += ["    },", "    names = {"]
lines += [f"        [{id}] = {lua_text(skills[id])}," for id in sorted(used_active)]
lines += [f"        [{id}] = {lua_text(passives[id])}," for id in sorted(used_passive)]
lines += ["    },", "}"]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
physical = sum(v["attackType"] == "Physic" for v in visions)
print(f"Wrote {physical} Physical Visions, {len(families)} family passives and "
      f"{len(used_active) + len(used_passive)} names to {OUT}")
