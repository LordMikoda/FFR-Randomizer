"""Builds mod/FFRRandomizer/Scripts/ItemNames.lua from the item CSV exports.

The spoiler log uses it to show item and Vision names. The mod still works
without it and falls back to item IDs. Run: py -3 -I tools/make_item_names.py
"""
import csv
import pathlib

EXPORTS = pathlib.Path("D:/AI Stuff/Exports/FFR Rando")
OUT = pathlib.Path(__file__).resolve().parent.parent / "mod/FFRRandomizer/Scripts/ItemNames.lua"
TABLES = [
    "DT_ConsumablesItemData.csv",
    "DT_EquipmentItemData.csv",
    "DT_ArtifactItemData.csv",
    "DT_ValuableItemData.csv",
    "DT_SeedItemData.csv",
    "DT_VisionItemData.csv",
]


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


names = {}
for table in TABLES:
    with open(EXPORTS / table, encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            names[int(row["ID"])] = row["Name (read only)"].strip() or row["RowKey"].strip()

lines = ["-- Generated by tools/make_item_names.py. Do not edit by hand.", "return {"]
lines += [f"    [{item_id}] = {lua_string(name)}," for item_id, name in sorted(names.items())]
lines.append("}")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Wrote {len(names)} names to {OUT}")
